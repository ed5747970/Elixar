        static int Col(string code) { return code == "ar" ? 1 : code == "ru" ? 2 : 3; }

        static Dictionary<string, string> BuildMore(string code)
        {
            var d = new Dictionary<string, string>();
            if (code != "ar" && code != "ru" && code != "es") return d;
            int c = Col(code);
            foreach (var r in More) d[r[0]] = r[c];
            // texts with numbers in them
            Func<string, string, string, string> w = (ar, ru, es) => c == 1 ? ar : c == 2 ? ru : es;
            Pat(@"Free (.+) safely", m => w("حرّر " + m.Groups[1].Value + " بأمان", "Освободить " + m.Groups[1].Value + " безопасно", "Liberar " + m.Groups[1].Value + " con seguridad"));
            Pat(@"Clean (\d+) \((.+)\)", m => w("تنظيف " + m.Groups[1].Value + " (" + m.Groups[2].Value + ")", "Очистить " + m.Groups[1].Value + " (" + m.Groups[2].Value + ")", "Limpiar " + m.Groups[1].Value + " (" + m.Groups[2].Value + ")"));
            Pat(@"Freed (.+?)( \(weekly clean\))?( · (.+) in all)?", m => w("تم تحرير ", "Освобождено ", "Liberado ") + m.Groups[1].Value + (m.Groups[2].Success ? w(" (التنظيف الأسبوعي)", " (еженедельная очистка)", " (limpieza semanal)") : "") +
                                                                       (m.Groups[3].Success ? " · " + m.Groups[4].Value + w(" إجمالًا", " всего", " en total") : ""));
            Pat(@"free of (.+)", m => w("متاح من ", "свободно из ", "libre de ") + m.Groups[1].Value);
            Pat(@"(\d+) days", m => m.Groups[1].Value + w(" يومًا", " дн.", " días"));
            Pat(@"Apply (\d+) changes?", m => w("تطبيق ", "Применить ", "Aplicar ") + m.Groups[1].Value);
            Pat(@"(.+) of caches and temp files can be freed safely: Windows and your apps rebuild them by themselves\.", m => w(
                "يمكن تحرير " + m.Groups[1].Value + " من الذاكرة المؤقتة والملفات المؤقتة بأمان: يعيد Windows وتطبيقاتك إنشاءها تلقائيًا.",
                m.Groups[1].Value + " кэша и временных файлов можно безопасно освободить: Windows и приложения создадут их заново.",
                "Se pueden liberar con seguridad " + m.Groups[1].Value + " de cachés y archivos temporales: Windows y sus aplicaciones los vuelven a crear."));
